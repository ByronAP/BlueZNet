namespace BlueZNet.Enums
{
    /// <summary>
    /// Represents the available Bluetooth audio profiles.
    /// </summary>
    public enum AudioProfile
    {
        /// <summary>
        /// Advanced Audio Distribution Profile - for high-quality music streaming.
        /// </summary>
        A2DP,

        /// <summary>
        /// Hands-Free Profile - for hands-free calling with audio.
        /// </summary>
        HFP,

        /// <summary>
        /// Headset Profile - for basic headset functionality.
        /// </summary>
        HSP,

        /// <summary>
        /// Audio/Video Remote Control Profile - for media control.
        /// </summary>
        AVRCP
    }
}
